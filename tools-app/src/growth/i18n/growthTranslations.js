/**
 * Current active language is 'en'. Additional dictionaries can be added to
 * growthTranslations and activated via setGrowthLanguage.
 */
let currentLanguage = 'en';

export const setGrowthLanguage = (lang) => {
  if (growthTranslations[lang]) {
    currentLanguage = lang;
  }
};

export const getGrowthLanguage = () => currentLanguage;

/**
 * Helper to get a translated string by dot notation path
 * Example: t('nav.actionFeed', 'Action Feed')
 */
export const t = (path, fallback = '') => {
  const keys = path.split('.');
  const dict = growthTranslations[currentLanguage] || growthTranslations.en;
  let val = keys.reduce((acc, k) => (acc && acc[k] !== undefined ? acc[k] : undefined), dict);

  if (val === undefined && currentLanguage !== 'en') {
    val = keys.reduce((acc, k) => (acc && acc[k] !== undefined ? acc[k] : undefined), growthTranslations.en);
  }

  return val !== undefined ? val : fallback || path;
};
